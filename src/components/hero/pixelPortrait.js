export function pixelColour(red, green, blue) {
  const luminance = red * 0.2126 + green * 0.7152 + blue * 0.0722
  return PIXEL_PALETTE[Math.min(6, Math.floor(luminance / 37))]
}

export function pixelLayout(width, height) {
  const mobile = width < 760
  const size = Math.min(mobile ? width * 0.95 : width * 0.56, height * (mobile ? 0.49 : 0.94))
  return { size, left: mobile ? (width - size) / 2 : width * 0.72 - size / 2, top: mobile ? height - size - 65 : height - size - 28, resolution: 128 }
}

